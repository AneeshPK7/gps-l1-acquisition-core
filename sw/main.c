/*
 * main.c - bare-metal PS application (Zynq-7000, Xilinx standalone BSP)
 *
 * 1. Hardware-in-the-loop self-test (report Section 6.1, "PS-PL testing"):
 *    for each directed test vector T1..T8 the PS loads 1 ms of samples into the
 *    capture buffer with AXI DMA (MM2S -> s_axis), runs the search and compares
 *    Doppler / code phase / peak / second peak / detection with the bit-true model.
 * 2. Cold-start search of all 32 PRNs on the last capture, as the receiver would
 *    do after power-up, with one status sentence per detected satellite sent to the
 *    flight controller over UART (NMEA-style $PGACQ).
 *
 * Build: Vitis "Empty Application (C)" on the exported XSA; add gps_acq.c,
 * main.c and test_vectors.h (generated by model/gen_vectors.py).
 */
#include <stdint.h>
#include "xparameters.h"
#include "xil_printf.h"
#include "xil_cache.h"
#include "xaxidma.h"
#include "gps_acq.h"
#include "test_vectors.h"

#ifndef ACQ_BASE
#define ACQ_BASE 0x43C00000u          /* AXI4-Lite base address (vivado/build.tcl) */
#endif
#ifndef DMA_DEV_ID
#define DMA_DEV_ID XPAR_AXIDMA_0_DEVICE_ID
#endif

#define BUDGET_CYCLES 100000u         /* 1 ms at 100 MHz */

static XAxiDma dma;

/* Load one millisecond (1024 words = 4096 samples) into the PL capture buffer. */
static int load_capture(const uint32_t *words)
{
    Xil_DCacheFlushRange((UINTPTR)words, ACQ_WORDS_PER_MS * sizeof(uint32_t));
    if (XAxiDma_SimpleTransfer(&dma, (UINTPTR)words, ACQ_WORDS_PER_MS * sizeof(uint32_t),
                               XAXIDMA_DMA_TO_DEVICE) != XST_SUCCESS)
        return -1;
    while (XAxiDma_Busy(&dma, XAXIDMA_DMA_TO_DEVICE))
        ;
    return 0;
}

static int dma_init(void)
{
    XAxiDma_Config *cfg = XAxiDma_LookupConfig(DMA_DEV_ID);
    if (!cfg || XAxiDma_CfgInitialize(&dma, cfg) != XST_SUCCESS)
        return -1;
    if (XAxiDma_HasSg(&dma))
        return -1;                                /* simple mode expected */
    XAxiDma_IntrDisable(&dma, XAXIDMA_IRQ_ALL_MASK, XAXIDMA_DMA_TO_DEVICE);
    return 0;
}

static void send_to_flight_controller(const acq_result_t *r)
{
    char line[96];
    acq_format_nmea(r, line, sizeof line);
    xil_printf("%s", line);          /* PS UART; route to the FC UART on the target board */
}

int main(void)
{
    acq_dev_t acq;
    acq_result_t r;
    int pass = 0;

    xil_printf("\r\nGPS L1 acquisition core - PS/PL test\r\n");
    if (dma_init() != 0) {
        xil_printf("AXI DMA init failed\r\n");
        return -1;
    }
    if (acq_init(&acq, ACQ_BASE, 2.0) != 0) {
        xil_printf("acquisition core not found at 0x%08x\r\n", ACQ_BASE);
        return -1;
    }

    /* ---------------- 1. hardware-in-the-loop directed tests ---------------- */
    for (int t = 0; t < TV_NUM; t++) {
        const tv_expected_t *e = &tv_expected[t];
        if (load_capture(tv_samples[t]) != 0) {
            xil_printf("DMA error\r\n");
            return -1;
        }
        acq_search(&acq, e->prn, &r);
        int ok = r.detected == e->detected && r.doppler_hz == e->k * 1000 &&
                 r.code_phase == e->tau && r.peak == e->peak && r.second == e->second &&
                 r.cycles < BUDGET_CYCLES;
        pass += ok;
        int ratio100 = r.second ? (int)((uint64_t)r.peak * 100u / r.second) : 0;
        xil_printf("%s PRN %2d: fd=%6d Hz  tau=%4d  P1/P2=%d.%02d  det=%d  cycles=%d  %s\r\n",
                   e->name, r.prn, r.doppler_hz, r.code_phase, ratio100 / 100, ratio100 % 100,
                   r.detected, (int)r.cycles, ok ? "PASS" : "FAIL");
    }
    xil_printf("HIL result: %d / %d PASS\r\n", pass, TV_NUM);

    /* ---------------- 2. cold-start search of all PRNs ---------------------- */
    acq_result_t all[ACQ_N_PRN];
    int n = acq_search_all(&acq, all);
    xil_printf("cold start: %d satellite(s) detected in last capture\r\n", n);
    for (int i = 0; i < ACQ_N_PRN; i++)
        if (all[i].detected)
            send_to_flight_controller(&all[i]);   /* hand-over to tracking would go here */

    return pass == TV_NUM ? 0 : 1;
}
